/* ===================================================================
 * hash.js — SHA-256 精确指纹
 * 优先使用 WebCrypto（异步，需安全上下文 localhost/https）；
 * 文件协议等非安全上下文自动降级到内置纯 JS 实现（同步包装为异步）。
 * 隐私设计：指纹全部本地计算，原文永不上传。
 * =================================================================== */

const hasCrypto = typeof crypto !== 'undefined' && typeof crypto.subtle !== 'undefined';

/** bytes -> hex */
function toHex(buf) {
  const bytes = buf instanceof Uint8Array ? buf : new Uint8Array(buf);
  let s = '';
  for (let i = 0; i < bytes.length; i++) s += bytes[i].toString(16).padStart(2, '0');
  return s;
}

/** UTF-8 编码（字符串 -> Uint8Array） */
export function utf8Bytes(str) {
  if (typeof TextEncoder !== 'undefined') return new TextEncoder().encode(str);
  // 极老环境降级
  const out = [];
  for (let i = 0; i < str.length; i++) {
    let c = str.codePointAt(i);
    if (c > 0xffff) i++;
    if (c < 0x80) out.push(c);
    else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000) out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else out.push(0xf0 | (c >> 18), 0x80 | ((c >> 12) & 63), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
  }
  return new Uint8Array(out);
}

/** 计算 bytes 的 sha256 hex */
export async function sha256Bytes(bytes) {
  const data = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (hasCrypto) {
    const buf = await crypto.subtle.digest('SHA-256', data);
    return toHex(buf);
  }
  return jsSha256Hex(data);
}

/** 计算字符串 sha256（UTF-8） */
export async function sha256Text(str) {
  return sha256Bytes(utf8Bytes(str));
}

/** 同步版本（用于非安全上下文之外仍需同步哈希的场景，如生成模拟交易哈希） */
export function sha256Sync(str) {
  return jsSha256Hex(utf8Bytes(str));
}

